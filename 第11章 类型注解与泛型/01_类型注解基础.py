# ============================================================
# 第11章 · 01 - 类型注解是什么
# ============================================================
#
# 一句话：类型注解就是给变量、函数"贴个类型标签"。
#
#   age: int          告诉别人：age 应该是个整数
#
# 三个要点先记住：
#   1. 它只是"标签"，写不写都能跑（Python 不强制）。
#   2. 作用是：让 IDE 给你更准的提示、让代码更好读。
#   3. 类型写错了 Python 也不会报错，但编辑器会标黄提醒你。
# ============================================================


# ----- 1. 给变量贴标签：变量名: 类型 = 值 -----
print("=== 1. 变量注解 ===")

name: str = "小林"        # 字符串
age: int = 25            # 整数
height: float = 1.78     # 小数
is_vip: bool = True      # 布尔

print(name, age, height, is_vip)


# ----- 2. 给函数贴标签：参数 和 返回值 -----
print("\n=== 2. 函数注解 ===")


# 参数 name 是 str，箭头后面的 str 是"返回值类型"
def greet(name: str) -> str:
    return f"你好，{name}"


print(greet("小林"))


# 没有返回值的函数，返回类型写 None
def log(msg: str) -> None:
    print("[日志]", msg)


log("启动成功")


# ----- 3. 注解不影响运行（关键认知）-----
print("\n=== 3. 注解只是提示，不会拦截 ===")


def double(n: int) -> int:
    return n * 2


# 标注是 int，但真传字符串进去 Python 照样跑（'ab'*2='abab'）
# 只有编辑器/mypy 会标黄提醒你"类型不对"
print("double(10) =", double(10))
print("double('ab') =", double("ab"))   # 能跑，但不推荐这么写
