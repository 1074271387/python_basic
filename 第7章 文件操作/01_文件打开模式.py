# ============================================================
# 第7章 · 01 - 文件打开模式
# ============================================================
#
# 文件操作是编程中最基本的 IO 技能之一。
#
# 生活类比：
#   文件就像一本笔记本：
#   - "r" 模式 → 只翻开来看，不能写
#   - "w" 模式 → 撕掉所有页，从头写
#   - "a" 模式 → 翻到最后一页，接着写
#   - "b" 模式 → 处理图片/视频等二进制内容
#   - "+" 模式 → 既能看又能写
#
# 对比其他语言：
#   Java  → new FileReader("file.txt") / new FileWriter("file.txt")
#   JS    → fs.readFileSync("file.txt") / fs.writeFileSync("file.txt")
#   Python → open("file.txt", "r")  简洁优雅
#
# ============================================================

import os
import tempfile

# 为了演示，我们在临时目录创建文件，不污染项目
DEMO_DIR = os.path.join(tempfile.gettempdir(), "python_ch7_demo")
os.makedirs(DEMO_DIR, exist_ok=True)

print(DEMO_DIR)

# ============================================================
# 一、open() 函数基础
# ============================================================
#
# 语法：open(file, mode='r', encoding=None, ...)
#
# 核心参数：
#   file     → 文件路径（字符串或 Path 对象）
#   mode     → 打开模式（默认 'r'）
#   encoding → 编码方式（文本模式常用 'utf-8'）

print("=== open() 函数基础 ===")

# 先创建一个演示文件
demo_file = os.path.join(DEMO_DIR, "demo.txt")

f = open(demo_file, "w", encoding="utf-8")
f.write("Hello, Python!\n")
f.write("文件操作入门\n")
f.close()   # ⚠️ 手动关闭，忘了关会导致资源泄露

# 读取刚才写入的内容
f = open(demo_file, "r", encoding="utf-8")
content = f.read()
f.close()

print(content)

# ============================================================
# 二、所有打开模式一览
# ============================================================
#
# 基础模式（必选其一）：
#   'r'  → 只读（默认）。文件不存在会报 FileNotFoundError
#   'w'  → 只写（覆盖）。文件不存在会创建，存在则清空
#   'a'  → 追加写入。文件不存在会创建，存在则在末尾追加
#   'x'  → 独占创建。文件已存在会报 FileExistsError
#
# 修饰模式（可组合）：
#   'b'  → 二进制模式（如 'rb'、'wb'）
#   't'  → 文本模式（默认，如 'rt' 等价于 'r'）
#   '+'  → 读写模式（如 'r+'、'w+'、'a+'）

