# ============================================================
# 第3章 · 01 - 列表基础：创建与索引
# ============================================================
#
# 列表（list）是 Python 中最常用的数据容器。
# 你可以把它想象成「一排带编号的格子」，每个格子里可以放任何东西。
#
# 对比其他语言：
#   Java  → ArrayList（但 Python 列表更灵活，不限制类型）
#   JS    → Array（非常像，Python 的列表几乎一样强大）
#
# ============================================================

# ============================================================
# 一、创建列表
# ============================================================

print("=== 创建列表 ===")

# 方式1：直接用方括号
fruits = ["苹果", "香蕉", "橘子", "西瓜"]
print("水果列表：", fruits)

# 方式2：空列表
empty1 = []
empty2 = list()
print("空列表：", empty1, empty2)

# 方式3：用 list() 把其他东西转成列表
chars = list("Hello")
print("字符串转列表：", chars)  # ['H', 'e', 'l', 'l', 'o']

nums = list(range(1, 6))
print("range转列表：", nums)   # [1, 2, 3, 4, 5]

# 列表里可以放不同类型的元素（这一点和 Java 的数组很不同）
mixed = [1, "你好", 3.14, True, None]
print("混合列表：", mixed)

# ============================================================
# 二、列表索引（取单个元素）
# ============================================================
#
# 索引规则和字符串完全一样：从 0 开始，支持负数索引
#
#   fruits = ["苹果", "香蕉", "橘子", "西瓜"]
#   正向索引：   0       1       2       3
#   负向索引：  -4      -3      -2      -1

print("\n=== 列表索引 ===")

print("完整列表：", fruits)
print("第1个 fruits[0]：", fruits[0])     # 苹果
print("第2个 fruits[1]：", fruits[1])     # 香蕉
print("最后一个 fruits[-1]：", fruits[-1]) # 西瓜
print("倒数第2个 fruits[-2]：", fruits[-2]) # 橘子

# 列表长度
print("列表长度 len(fruits)：", len(fruits))  # 4

# ⚠️ 索引越界会报错
# print(fruits[10])  # IndexError: list index out of range

# ============================================================
# 三、修改元素（列表是可变的！）
# ============================================================
#
# 这是列表和字符串的最大区别：
#   字符串不可变 → "abc"[0] = "x"  会报错
#   列表可变     → [1,2,3][0] = 9  完全OK

print("\n=== 修改元素 ===")

scores = [90, 85, 78, 92]
print("原始成绩：", scores)

scores[2] = 88   # 把第3个成绩从78改为88
print("修改后：", scores)

scores[-1] = 95  # 把最后一个改为95
print("再次修改：", scores)

# ============================================================
# 四、列表的基本操作
# ============================================================

print("\n=== 列表基本操作 ===")

# 1. 拼接（+ 号）
list_a = [1, 2, 3]
list_b = [4, 5, 6]
combined = list_a + list_b
print("拼接：", combined)  # [1, 2, 3, 4, 5, 6]

# 2. 重复（* 号）
repeated = [0] * 5
print("重复：", repeated)  # [0, 0, 0, 0, 0]

# 3. 成员判断（in）
print("3 in list_a →", 3 in list_a)      # True
print("7 in list_a →", 7 in list_a)      # False
print("7 not in list_a →", 7 not in list_a)  # True

# 4. 统计
numbers = [1, 2, 3, 2, 1, 2, 4]
print(f"\n数字列表：{numbers}")
print("2 出现的次数：", numbers.count(2))  # 3
print("3 的位置索引：", numbers.index(3))  # 2（返回第一次出现的位置）

# 5. 最大值、最小值、求和
nums = [10, 5, 8, 3, 7]
print(f"\nnums = {nums}")
print("最大值：", max(nums))   # 10
print("最小值：", min(nums))   # 3
print("求和：", sum(nums))     # 33

# ============================================================
# 五、遍历列表
# ============================================================

print("\n=== 遍历列表 ===")

# 方式1：直接遍历元素（最常用）
print("--- 直接遍历 ---")
for fruit in fruits:
    print(f"  我喜欢吃{fruit}")

# 方式2：通过索引遍历
print("\n--- 索引遍历 ---")
for i in range(len(fruits)):
    print(f"  第{i+1}个水果是：{fruits[i]}")

# 方式3：enumerate 同时拿到索引和元素（推荐！）
print("\n--- enumerate 遍历（推荐） ---")
for index, fruit in enumerate(fruits):
    print(f"  [{index}] {fruit}")

# enumerate 还可以指定起始编号
print("\n--- enumerate 从1开始 ---")
for num, fruit in enumerate(fruits, start=1):
    print(f"  第{num}种：{fruit}")

# ============================================================
# 核心总结
# ============================================================
# 1. 列表用 [] 创建，可以存放任意类型的元素
# 2. 索引从 0 开始，支持负数索引，-1 是最后一个
# 3. 列表是可变的，可以直接通过索引修改元素
# 4. 常用操作：len()、in、count()、index()、max()、min()、sum()
# 5. 遍历推荐用 enumerate()，可以同时拿到索引和元素
