# ============================================================
# 一、可变对象 vs 不可变对象
# ============================================================

print("=== 可变 vs 不可变 ===")

print("""
┌─────────────────────────────────────────────┐
│     Python 对象的可变性分类                   │
├──────────────┬──────────────────────────────┤
│  不可变对象   │ int, float, str, bool,       │
│  (immutable) │ tuple, frozenset, None        │
├──────────────┼──────────────────────────────┤
│  可变对象     │ list, dict, set              │
│  (mutable)   │                              │
└──────────────┴──────────────────────────────┘
""")

# --- 不可变对象：修改时会创建新对象 ---
print("--- 不可变对象 ---")

a = 10
print(f"a = {a}，id = {id(a)}")
a = 20  # 不是修改10，而是让 a 指向了新的对象20
print(f"a = {a}，id = {id(a)}（id变了，说明是新对象）")

s = "hello"
print(f"\ns = '{s}'，id = {id(s)}")
s = s + " world"  # 创建了一个新的字符串
print(f"s = '{s}'，id = {id(s)}（id变了）")

# --- 可变对象：可以在原地修改 ---
print("\n--- 可变对象 ---")

lst = [1, 2, 3]
print(f"lst = {lst}，id = {id(lst)}")
lst.append(4)
print(f"lst = {lst}，id = {id(lst)}（id没变，还是同一个对象！）")

lst[0] = 99
print(f"lst = {lst}，id = {id(lst)}（id还是没变）")

# ============================================================
# 二、变量赋值的本质：绑定引用
# ============================================================
#
# Python 的变量不是"盒子"，而是"标签"。
# a = [1,2,3] 不是把 [1,2,3] 放进叫 a 的盒子里，
# 而是把"标签 a"贴到 [1,2,3] 这个对象上。

print("\n=== 变量赋值的本质 ===")

# 不可变对象的赋值
x = 100
y = x       # y 和 x 指向同一个对象
print(f"x={x}, y={y}, x is y → {x is y}")

x = 200     # x 指向了新对象，y 不受影响
print(f"x={x}, y={y}")
print("  → 不可变对象：重新赋值不影响其他变量")

# 可变对象的赋值（坑来了！）
list_a = [1, 2, 3]
list_b = list_a   # list_b 和 list_a 指向同一个列表！
print(f"\nlist_a = {list_a}")
print(f"list_b = {list_b}")
print(f"list_a is list_b → {list_a is list_b}")

list_b.append(4)  # 通过 list_b 修改
print(f"\n修改 list_b 后：")
print(f"list_a = {list_a}")  # list_a 也变了！
print(f"list_b = {list_b}")
print("  → 可变对象：赋值只是创建了别名，修改一个会影响另一个！")

# ============================================================
# 三、浅拷贝（Shallow Copy）
# ============================================================
#
# 浅拷贝：创建新的容器，但里面的元素还是引用原来的对象

print("\n=== 浅拷贝 ===")

import copy

# --- 对于一维列表，浅拷贝足够安全 ---
original = [1, 2, 3, 4, 5]
shallow = original.copy()   # 浅拷贝（等价于 copy.copy(original)）

shallow[0] = 999
print("一维列表浅拷贝：")
print(f"  original = {original}")  # 不受影响
print(f"  shallow  = {shallow}")
print(f"  original is shallow → {original is shallow}")  # False

# --- 对于嵌套列表，浅拷贝有坑！ ---
print("\n--- 嵌套列表的浅拷贝（有坑！） ---")

nested = [[1, 2], [3, 4], [5, 6]]
shallow_nested = nested.copy()  # 浅拷贝

# 修改外层：互不影响
shallow_nested.append([7, 8])
print(f"添加新元素后：")
print(f"  original = {nested}")        # 没有 [7, 8]
print(f"  shallow  = {shallow_nested}")  # 有 [7, 8]

# 修改内层：相互影响！
shallow_nested[0][0] = 999
print(f"\n修改内层元素后：")
print(f"  original = {nested}")        # [[999, 2], ...] 也变了！
print(f"  shallow  = {shallow_nested}")

print("""
  原因：浅拷贝只拷贝了"第一层"。
  nested[0] 和 shallow_nested[0] 指向的是同一个 [1,2] 列表。
  修改其中一个，另一个也会变。

  图示：
  nested ──────→ [ ●, ●, ● ]
                   │  │  │
  shallow ─────→ [ ●, ●, ●, [7,8] ]
                   │  │  │
                   ↓  ↓  ↓
                 [1,2] [3,4] [5,6]   ← 共享同一组内部列表
""")

# 浅拷贝的3种等价写法
lst = [1, [2, 3], 4]
c1 = lst.copy()         # 方式1
c2 = lst[:]             # 方式2
c3 = list(lst)          # 方式3
c4 = copy.copy(lst)     # 方式4
print("4种浅拷贝方式都是等价的")

# ============================================================
# 四、深拷贝（Deep Copy）
# ============================================================
#
# 深拷贝：递归地拷贝所有层级，完全独立

print("\n=== 深拷贝 ===")

nested_original = [[1, 2], [3, 4], {"key": [5, 6]}]

# 深拷贝
deep = copy.deepcopy(nested_original)

# 修改深拷贝的内容
deep[0][0] = 999
deep[2]["key"].append(7)

print("深拷贝后修改：")
print(f"  original = {nested_original}")   # 完全不受影响！
print(f"  deep     = {deep}")

print("""
  深拷贝递归地复制了所有层级的对象，
  修改任何一层都不会影响另一个。
""")

# ============================================================
# 五、字典的拷贝
# ============================================================

print("=== 字典的拷贝 ===")

# 浅拷贝
user = {
    "name": "小明",
    "scores": [90, 85, 78],
    "info": {"city": "北京"}
}

# 浅拷贝
user_copy = user.copy()
user_copy["name"] = "小红"        # 修改不可变值 → 不影响原字典
user_copy["scores"].append(100)   # 修改可变值 → 影响原字典！

print(f"原字典 user   = {user}")
print(f"浅拷贝 user_copy = {user_copy}")
print("  → name 各自独立，但 scores 共享！")

# 深拷贝
user2 = copy.deepcopy(user)
user2["scores"].append(200)
user2["info"]["city"] = "上海"

print(f"\n原字典 user  = {user}")       # 不受影响
print(f"深拷贝 user2 = {user2}")

# ============================================================
# 六、函数参数传递
# ============================================================
#
# Python 的参数传递本质上是"传引用"（传对象的引用）
# 但表现行为取决于对象是否可变

print("\n=== 函数参数传递 ===")

# 不可变对象：函数内修改不影响外部
def try_modify_int(x):
    x = x + 10
    print(f"  函数内：x = {x}")

num = 5
print(f"调用前：num = {num}")
try_modify_int(num)
print(f"调用后：num = {num}")  # 还是5
print("  → 不可变对象在函数内修改不影响外部\n")

# 可变对象：函数内修改会影响外部！
def try_modify_list(lst):
    lst.append(99)
    print(f"  函数内：lst = {lst}")

my_list = [1, 2, 3]
print(f"调用前：my_list = {my_list}")
try_modify_list(my_list)
print(f"调用后：my_list = {my_list}")  # 被改了！
print("  → 可变对象在函数内修改会影响外部！")

# 如果不想被修改，传拷贝进去
print(f"\n--- 传拷贝防止被修改 ---")
my_list2 = [1, 2, 3]
try_modify_list(my_list2.copy())   # 传拷贝
print(f"原列表不变：my_list2 = {my_list2}")

