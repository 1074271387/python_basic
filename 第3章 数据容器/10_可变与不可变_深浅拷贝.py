# 七、常见陷阱
# ============================================================

print("\n=== 常见陷阱 ===")

# 陷阱1：用 * 创建的嵌套列表共享引用
print("--- 陷阱1：* 创建嵌套列表 ---")
matrix_bad = [[0] * 3] * 3   # ❌ 三行指向同一个列表
matrix_bad[0][0] = 1
print(f"  matrix_bad = {matrix_bad}")
print("  → 修改一行，三行都变了！")

matrix_good = [[0] * 3 for _ in range(3)]  # ✅ 每行独立
matrix_good[0][0] = 1
print(f"  matrix_good = {matrix_good}")
print("  → 只有第一行变了")

# 陷阱2：默认参数用可变对象
print("\n--- 陷阱2：默认参数用可变对象 ---")

def bad_append(item, lst=[]):  # ❌ 默认参数在函数定义时就创建了
    lst.append(item)
    return lst

print(f"  第1次调用：{bad_append(1)}")  # [1]
print(f"  第2次调用：{bad_append(2)}")  # [1, 2] ← 不是 [2]！
print(f"  第3次调用：{bad_append(3)}")  # [1, 2, 3]
print("  → 默认列表被所有调用共享了！")

def good_append(item, lst=None):  # ✅ 正确写法
    if lst is None:
        lst = []
    lst.append(item)
    return lst

print(f"\n  修正后第1次：{good_append(1)}")  # [1]
print(f"  修正后第2次：{good_append(2)}")  # [2] ← 正确！

