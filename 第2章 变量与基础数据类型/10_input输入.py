# ============================================================
# 第2章 · 10 - 输入与输出（input / print）
# ============================================================
#
# print() 我们已经很熟了，它是"输出"，让电脑显示信息。
# input() 是"输入"，让用户从键盘输入信息给程序。
#
# 把它们结合起来，就能和用户"对话"了！
#
# ============================================================

# ============================================================
# 一、input() 基础
# ============================================================
#
# input() 会暂停程序，等你在键盘上输入一些东西，按回车后继续。
# ⚠️ 重要：input() 返回的永远是字符串（str），不管你输入的是什么！

print("=== input() 基础 ===")

name = input("请输入你的名字：")
print(f"你好，{name}！欢迎来到 Python 世界！")
print(f"你的名字类型是：{type(name)}")   # 一定是 <class 'str'>

# ============================================================
# 二、input() + 类型转换
# ============================================================
# 如果想拿输入的数字做运算，必须先转换类型

print("\n=== 输入数字并计算 ===")

age_str = input("请输入你的年龄：")
age = int(age_str)   # 把字符串转成整数
print(f"你今年 {age} 岁，明年就 {age + 1} 岁了！")

# 也可以把 input 和 int 写在一行里（更简洁）
# age = int(input("请输入你的年龄："))

# ============================================================
# 三、小计算器
# ============================================================

print("\n=== 小计算器 ===")

num1 = float(input("请输入第一个数字："))
num2 = float(input("请输入第二个数字："))

print(f"\n计算结果：")
print(f"  {num1} + {num2} = {num1 + num2}")
print(f"  {num1} - {num2} = {num1 - num2}")
print(f"  {num1} × {num2} = {num1 * num2}")

if num2 != 0:
    print(f"  {num1} ÷ {num2} = {num1 / num2:.2f}")
else:
    print("  除数不能为 0！")

# ============================================================
# 四、print() 进阶
# ============================================================

print("\n=== print() 进阶用法 ===")

# sep 参数：控制多个值之间的分隔符（默认是空格）
print("苹果", "香蕉", "橘子")                # 苹果 香蕉 橘子
print("苹果", "香蕉", "橘子", sep="、")       # 苹果、香蕉、橘子
print("苹果", "香蕉", "橘子", sep=" → ")      # 苹果 → 香蕉 → 橘子
print(2025, 3, 4, sep="-")                     # 2025-3-4

# end 参数：控制末尾字符（默认是换行符 \n）
print("加载中", end="")
print(".", end="")
print(".", end="")
print(".")    # 加载中...

