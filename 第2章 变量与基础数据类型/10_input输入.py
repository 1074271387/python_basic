# 五、综合练习：自我介绍生成器
# ============================================================

print("\n" + "=" * 40)
print("   ✨ 自我介绍生成器 ✨")
print("=" * 40)

user_name = input("你叫什么名字？ ")
user_age = input("你多大了？ ")
user_hobby = input("你的爱好是什么？ ")

print(f"""
{'=' * 40}
大家好！
我叫{user_name}，今年{user_age}岁。
我最大的爱好是{user_hobby}。
很高兴认识大家！
{'=' * 40}
""")

