# ============================================================
# 第2章 · 02 - 变量是什么
# ============================================================
#
# 【生活中的比喻】
#
# 想象你面前有很多个「盒子」：
#   - 每个盒子上面都贴了一个「标签」（名字）
#   - 盒子里面可以放一个「东西」（值）
#
# 比如：
#   有一个盒子，标签写着"age"，里面放着数字 18
#   有一个盒子，标签写着"name"，里面放着文字 "小明"
#
# 在 Python 里，这个「贴了标签的盒子」就叫做【变量】。
#
# 变量 = 一个用来存放数据的容器
# 变量名 = 盒子上的标签
# 变量值 = 盒子里面放的东西
#
# ============================================================

# --- 创建变量 ---
# 语法非常简单：变量名 = 值
# 这个 "=" 不是数学里的"等于"，而是"赋值"的意思
# 意思是：把右边的值，放进左边这个名字的盒子里

age = 18
name = "小明"
height = 1.75

# 用 print 看看盒子里装了什么
print("姓名：", name)
print("年龄：", age)
print("身高：", height)

# --- 变量可以随时更换里面的值 ---
# 就像你可以把盒子里的东西拿出来，换一个新的放进去

print("\n--- 变量的值可以改变 ---")

score = 60
print("期中考试成绩：", score)

score = 90
print("期末考试成绩：", score)
# 注意：盒子(score)还是那个盒子，但里面的东西从 60 变成了 90

# --- 变量可以存不同类型的数据 ---
print("\n--- 变量里可以放各种东西 ---")

a = 100        # 放一个整数
print("a 里面是：", a)

a = "一百"     # 换成一段文字
print("a 里面变成了：", a)

a = True       # 换成一个对/错的判断
print("a 里面又变成了：", a)

# --- 多个变量同时赋值 ---
print("\n--- 同时创建多个变量 ---")

x, y, z = 1, 2, 3
print("x =", x, ", y =", y, ", z =", z)

# 让多个变量指向同一个值
a = b = c = 0
print("a =", a, ", b =", b, ", c =", c)

# --- 交换两个变量的值 ---
print("\n--- 交换两个变量 ---")

left = "左手拿着苹果"
right = "右手拿着香蕉"
print("交换前：", left, "|", right)

left, right = right, left
print("交换后：", left, "|", right)

# --- 核心总结 ---
# 1. 变量就是一个"贴了标签的盒子"，用来存放数据
# 2. 用 = 号把值放进变量里（赋值）
# 3. 变量的值可以随时更改
# 4. 变量名就是你给盒子取的名字，下一节课会讲命名规范
