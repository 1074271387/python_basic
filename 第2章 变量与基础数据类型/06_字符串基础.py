# ============================================================
# 第2章 · 06 - 字符串基础（定义、索引、切片）
# ============================================================
#
# 字符串（str）就是「一串文字」。
# 在 Python 里，只要用引号括起来的东西，都是字符串：
#   "你好"  '世界'  "123"  'True'
#
# 注意："123" 是字符串（文字），123 是数字，它们完全不同！
#   "123" + "456" = "123456"（文字拼接）
#   123 + 456 = 579（数学加法）
#
# ============================================================

# ============================================================
# 一、字符串的定义方式
# ============================================================

print("=== 字符串的多种写法 ===")

# 方式1：单引号
s1 = '你好世界'
print(s1)

# 方式2：双引号
s2 = "你好世界"
print(s2)

# 方式3：三引号（可以跨越多行）
s3 = """这是第一行
这是第二行
这是第三行"""
print(s3)

# 什么时候用单引号，什么时候用双引号？
# 当字符串里面有引号时，外面用另一种：
quote1 = "他说：'你好'"
quote2 = '他说："你好"'
print(quote1)
print(quote2)

# 也可以用反斜杠转义：
quote3 = "他说：\"你好\""
print(quote3)

# 常见的转义字符：
print("\n=== 常见转义字符 ===")
print("换行符：第一行\n第二行")
print("制表符：姓名\t年龄\t成绩")
print("反斜杠：C:\\Users\\Desktop")

# ============================================================
# 二、字符串的索引（取单个字符）
# ============================================================
#
# 字符串里的每个字符都有一个编号（索引），从 0 开始。
#
# 比如 "Python" 这个字符串：
#  字符：  P   y   t   h   o   n
#  正向：  0   1   2   3   4   5
#  反向： -6  -5  -4  -3  -2  -1
#
# 为什么从0开始？这是计算机的传统，你只需要记住就好。

print("\n=== 字符串索引 ===")

word = "Python"

print("完整字符串：", word)
print("第1个字符 word[0]：", word[0])    # P
print("第2个字符 word[1]：", word[1])    # y
print("第3个字符 word[2]：", word[2])    # t
print("最后1个 word[-1]：", word[-1])    # n
print("倒数第2个 word[-2]：", word[-2])  # o

# 字符串的长度
print("字符串长度 len(word)：", len(word))  # 6

# ============================================================
# 三、字符串的切片（取一段字符）
# ============================================================
#
# 切片就像切面包：从第几片切到第几片
# 语法：字符串[起始:结束]
# 注意：包含起始，不包含结束（左闭右开）
#
# 口诀：切片是 "从哪开始，到哪停下（但不包括停下的位置）"

print("\n=== 字符串切片 ===")

text = "Hello Python"
#       0123456789...

print("原字符串：", text)
print("text[0:5] →", text[0:5])     # Hello（从0到5，不包括5）
print("text[6:12] →", text[6:12])   # Python
print("text[:5] →", text[:5])       # Hello（省略起始 = 从头开始）
print("text[6:] →", text[6:])       # Python（省略结束 = 到末尾）
print("text[:] →", text[:])         # Hello Python（全部复制）

# 带步长的切片：字符串[起始:结束:步长]
print("\n--- 带步长的切片 ---")
numbers = "0123456789"

print("原字符串：", numbers)
print("每隔一个取：numbers[::2] →", numbers[::2])    # 02468
print("每隔两个取：numbers[::3] →", numbers[::3])    # 0369
print("反转字符串：numbers[::-1] →", numbers[::-1])   # 9876543210

# 实用例子：反转字符串
name = "你好世界"
print(f"'{name}' 反转后 → '{name[::-1]}'")

# ============================================================
# 四、字符串拼接
# ============================================================

print("\n=== 字符串拼接 ===")

first_name = "小"
last_name = "明"

full_name = first_name + last_name
print("姓名：", full_name)

# 字符串重复
line = "-" * 30
print(line)
print("分隔线就是这么来的")
print(line)

# ⚠️ 字符串不能直接和数字拼接！
# print("年龄是" + 18)  # ❌ 会报错
print("年龄是" + str(18))  # ✅ 先把数字转成字符串

# ============================================================
# 核心总结
# ============================================================
# 1. 字符串用引号括起来：'' "" """ """
# 2. 索引从 0 开始，-1 是最后一个
# 3. 切片 [起始:结束]，左闭右开
# 4. [::-1] 可以反转字符串
# 5. + 拼接字符串，* 重复字符串
