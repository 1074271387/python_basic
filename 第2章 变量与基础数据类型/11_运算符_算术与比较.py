# 第2章 · 11 - 运算符（一）：算术运算符与比较运算符
# ============================================================
#
# 运算符就是用来"做运算"的符号。
# 就像数学课上学的 +、-、×、÷ 一样，
# Python 也有自己的一套运算符。
#
# ============================================================

# ============================================================
# 一、算术运算符
# ============================================================
print("=== 算术运算符 ===")

a = 17
b = 5

print(f"a = {a}, b = {b}")
print(f"加法    a + b  = {a + b}")     # 22
print(f"减法    a - b  = {a - b}")     # 12
print(f"乘法    a * b  = {a * b}")     # 85
print(f"除法    a / b  = {a / b}")     # 3.4（永远返回浮点数）
print(f"整除    a // b = {a // b}")    # 3（只取整数部分）
print(f"取余    a % b  = {a % b}")     # 2（17 ÷ 5 = 3 余 2）
print(f"幂运算  a ** b = {a ** b}")    # 17 的 5 次方

# --- 整除和取余的实际应用 ---
print("\n--- 整除和取余的实际用途 ---")

total_seconds = 3725

hours = total_seconds // 3600
minutes = (total_seconds % 3600) // 60
seconds = total_seconds % 60

print(f"{total_seconds} 秒 = {hours}小时{minutes}分钟{seconds}秒")

# 判断奇偶数
number = 7
if number % 2 == 0:
    print(f"{number} 是偶数")
else:
    print(f"{number} 是奇数")

# --- 运算优先级 ---
print("\n--- 运算优先级 ---")

# 和数学一样：先乘除后加减，括号优先
print("2 + 3 * 4 =", 2 + 3 * 4)       # 14（先算 3*4=12，再 2+12）
print("(2 + 3) * 4 =", (2 + 3) * 4)   # 20（括号优先）

# 优先级从高到低：
# **（幂）> 正负号 > * / // % > + -
# 不确定的时候，加括号就对了！

print("2 ** 3 ** 2 =", 2 ** 3 ** 2)     # 512（幂运算从右往左：先算3**2=9，再算2**9=512）
print("(2 ** 3) ** 2 =", (2 ** 3) ** 2) # 64

# ============================================================
# 二、比较运算符
# ============================================================
#
# 比较运算符用来比较两个值的大小关系，
# 结果是布尔值：True 或 False

print("\n=== 比较运算符 ===")

x = 10
y = 20

print(f"x = {x}, y = {y}")
print(f"x == y  等于？     {x == y}")     # False
print(f"x != y  不等于？   {x != y}")     # True
print(f"x > y   大于？     {x > y}")      # False
print(f"x < y   小于？     {x < y}")      # True
print(f"x >= y  大于等于？ {x >= y}")     # False
print(f"x <= y  小于等于？ {x <= y}")     # True

# --- ⚠️ = 和 == 的区别 ---
print("\n--- = 和 == 完全不同！ ---")
# =  是赋值：把右边的值放进左边的变量
# == 是比较：判断左右两边是否相等
score = 100       # 赋值：把 100 放进 score
print(score == 100)  # 比较：score 等于 100 吗？True

# --- 链式比较（Python 特有！） ---
print("\n--- 链式比较 ---")

age = 25
print(f"age = {age}")
print(f"18 <= age <= 60 → {18 <= age <= 60}")  # True

score = 85
print(f"score = {score}")
print(f"80 <= score < 90 → {80 <= score < 90}")  # True，是不是比其他语言优雅？

# --- 字符串也能比较 ---
print("\n--- 字符串比较 ---")

print('"apple" == "apple" →', "apple" == "apple")   # True
print('"apple" == "Apple" →', "apple" == "Apple")   # False（大小写不同）
print('"apple" < "banana" →', "apple" < "banana")   # True（按字典顺序比较）

# 字符串比较按字符的编码值（a=97, b=98, ... A=65, B=66, ...）
# 所以大写字母 < 小写字母

# ============================================================
# 核心总结
# ============================================================
# 算术运算符：+ - * / // % **
# 比较运算符：== != > < >= <=
# = 是赋值，== 是比较，不要搞混！
# Python 支持链式比较：18 <= age <= 60
# 不确定优先级？加括号！
