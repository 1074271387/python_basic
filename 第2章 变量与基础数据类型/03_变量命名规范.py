# ============================================================
# 第2章 · 03 - 变量命名规范
# ============================================================
#
# 上节课我们知道了变量是"贴了标签的盒子"，
# 那这个标签（变量名）不是随便乱写的，有几条规矩要遵守。
#
# ============================================================

# ============================================================
# 规则一：变量名只能包含 字母、数字、下划线（_）
# ============================================================

my_name = "小明"      # ✅ 合法：字母和下划线
age2 = 20             # ✅ 合法：字母和数字
_secret = "隐藏数据"   # ✅ 合法：下划线开头也可以

# 下面这些是非法的（取消注释会报错）：
# my-name = "小明"    # ❌ 不能用减号（-）
# my name = "小明"    # ❌ 不能有空格
# 2age = 20           # ❌ 不能以数字开头
# my@name = "小明"    # ❌ 不能用特殊符号

# ============================================================
# 规则二：不能以数字开头
# ============================================================

student1 = "张三"      # ✅ 数字在后面没问题
# 1student = "张三"    # ❌ 数字在开头不行

# ============================================================
# 规则三：不能使用 Python 的「关键字」作为变量名
# ============================================================
# 关键字是 Python 自己要用的特殊单词，你不能抢过来当变量名

# 下面是一些常见关键字（了解即可，不用背）：
# if, else, for, while, True, False, None, and, or, not,
# def, class, return, import, from, as, try, except, ...

# 怎么查看所有关键字？
import keyword
print("Python 关键字列表：")
print(keyword.kwlist)
print("一共有", len(keyword.kwlist), "个关键字")

# 下面这些会报错（取消注释可以试试）：
# if = 10        # ❌ "if" 是关键字
# class = "高三"  # ❌ "class" 是关键字

# ============================================================
# 规则四：变量名区分大小写
# ============================================================

Name = "小明"
name = "小红"
NAME = "小刚"

print("\nName =", Name)
print("name =", name)
print("NAME =", NAME)
# 这三个是完全不同的变量！

# ============================================================
# 【推荐的命名风格】
# ============================================================
#
# Python 社区推荐使用「蛇形命名法」（snake_case）：
#   - 所有字母小写
#   - 单词之间用下划线连接
#
# 例如：

student_name = "张三"        # ✅ 推荐：蛇形命名法
student_age = 18             # ✅ 推荐
total_score = 280            # ✅ 推荐

# 不推荐的写法（但语法上不会报错）：
studentName = "张三"         # ⚠️ 驼峰命名法，Java/JS 风格，Python 不推荐
StudentName = "张三"         # ⚠️ 大驼峰，Python 里一般用来命名类
STUDENT_NAME = "张三"        # ⚠️ 全大写，Python 里一般用来表示常量

# ============================================================
# 【起名的好习惯】
# ============================================================

# ✅ 好名字：看名字就知道里面放的什么
user_age = 25
max_retry_count = 3
is_logged_in = True

# ❌ 坏名字：不知所云
a = 25
x = 3
flag = True

# ============================================================
# 核心总结
# ============================================================
# 1. 只能用字母、数字、下划线，且不能以数字开头
# 2. 不能用 Python 关键字
# 3. 区分大小写（name 和 Name 是两个不同变量）
# 4. 推荐 snake_case（蛇形命名法）
# 5. 变量名要有意义，让人一看就懂

print("\n--- 命名对比 ---")
print("好的命名：user_age, max_score, is_vip")
print("差的命名：a, b, x, tmp, data")
