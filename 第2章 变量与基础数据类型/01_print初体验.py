# ============================================================
# 第2章 · 01 - print 初体验
# ============================================================
# 学编程的第一步，就是让电脑"说话"。
# print() 就是 Python 里让电脑在屏幕上显示文字的命令。
#
# 你可以把 print() 想象成一个"喇叭"：
#   你把想说的话放进喇叭里，电脑就会把它喊出来。
# ============================================================

# --- 最简单的 print ---
# 把想显示的文字用引号括起来，放进 print() 的括号里

# 我是注释

print("你好，世界！")
print("Hello, World!")

# --- 引号的两种写法 ---
# 单引号和双引号都可以，效果完全一样
print('用单引号也行')
print("用双引号也行")

# --- 打印数字 ---
# 数字不需要加引号
print(100)
print(3.14)

# --- 一次打印多个东西 ---
# 用逗号隔开，Python 会自动在它们之间加一个空格
print("我的名字是", "小明")
print("我今年", 18, "岁")
print("1 + 1 =", 2)

# --- 打印空行 ---
# 什么都不放，就会输出一个空行
print()

# --- print 的换行行为 ---
# 每次 print 默认会在末尾加一个换行符（就是按了一下回车）
# 所以下面两句话会显示在两行：
print("第一行")
print("第二行")

# 如果你不想换行，可以用 end 参数：
print("我不换行", end="")
print("——看，我们在同一行！")

# 也可以用别的符号代替换行：
print("苹果", end="、")
print("香蕉", end="、")
print("橘子")

