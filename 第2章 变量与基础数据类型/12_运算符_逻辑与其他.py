# ============================================================
# 一、逻辑运算符：and / or / not
# ============================================================
#
# 逻辑运算符用来组合多个条件，结果也是 True 或 False。
#
# and（并且）：两个都为真，结果才为真
# or （或者）：只要有一个为真，结果就为真
# not（取反）：真变假，假变真

print("=== 逻辑运算符 ===")

age = 25
has_id = True

# and：两个条件都满足
print(f"age >= 18 and has_id → {age >= 18 and has_id}")  # True
# 翻译：年龄>=18 并且 有身份证 → 可以办理业务

# or：满足一个就行
has_cash = False
has_card = True
print(f"has_cash or has_card → {has_cash or has_card}")   # True
# 翻译：有现金 或者 有银行卡 → 可以付款

# not：取反
is_raining = False
print(f"not is_raining → {not is_raining}")               # True
# 翻译：没有下雨 → True

# --- 组合使用 ---
print("\n--- 组合判断 ---")

score = 85
attendance = 0.9  # 出勤率 90%

passed = score >= 60 and attendance >= 0.8
print(f"成绩{score}分，出勤{attendance*100}%")
print(f"是否通过？{passed}")  # True

# 优先级：not > and > or
# 不确定时加括号：
result = (score >= 90) or (score >= 60 and attendance >= 0.9)
print(f"是否获得奖学金？{result}")

# --- 短路求值（了解） ---
print("\n--- 短路求值 ---")
# and：如果第一个条件为 False，第二个条件不会执行
# or ：如果第一个条件为 True，第二个条件不会执行

# Python 中 and/or 返回的不一定是 True/False，而是决定结果的那个值
print("1 and 2 →", 1 and 2)     # 2（第一个为真，看第二个，返回第二个）
print("0 and 2 →", 0 and 2)     # 0（第一个为假，直接返回第一个）
print("1 or 2  →", 1 or 2)      # 1（第一个为真，直接返回第一个）
print("0 or 2  →", 0 or 2)      # 2（第一个为假，看第二个，返回第二个）

# 实用技巧：给变量设默认值
username = ""
display_name = username or "未登录"
print(f"显示名称：{display_name}")  # 匿名用户

# ============================================================
# 二、赋值运算符
# ============================================================
print("\n=== 赋值运算符 ===")

# 基本赋值
x = 10
print(f"x = {x}")

# 复合赋值（边运算边赋值，偷懒写法）
x += 5    # 等同于 x = x + 5
print(f"x += 5  → x = {x}")     # 15

x -= 3    # 等同于 x = x - 3
print(f"x -= 3  → x = {x}")     # 12

x *= 2    # 等同于 x = x * 2
print(f"x *= 2  → x = {x}")     # 24

x //= 5   # 等同于 x = x // 5
print(f"x //= 5 → x = {x}")    # 4

x **= 3   # 等同于 x = x ** 3
print(f"x **= 3 → x = {x}")    # 64

x %= 10   # 等同于 x = x % 10
print(f"x %= 10 → x = {x}")    # 4

# ⚠️ Python 没有 ++ 和 -- 运算符（C/Java/JS 里有）
# 想加1只能写 x += 1

# ============================================================
# 三、成员运算符：in / not in
# ============================================================
#
# 用来判断某个东西是否在某个"容器"里

print("\n=== 成员运算符 in ===")

# 字符串中查找
sentence = "我爱学Python"
print(f"'Python' in '{sentence}' → {'Python' in sentence}")  # True
print(f"'Java' in '{sentence}'   → {'Java' in sentence}")    # False

# 列表中查找（列表后面会详细学）
fruits = ["苹果", "香蕉", "橘子"]
print(f"\n水果列表：{fruits}")
print(f"'香蕉' in fruits → {'香蕉' in fruits}")        # True
print(f"'西瓜' not in fruits → {'西瓜' not in fruits}") # True

# ============================================================
# 四、身份运算符：is / is not
# ============================================================
#
# is 判断两个变量是否指向同一个对象（内存地址相同）
# == 判断两个变量的值是否相等
#
# 类比：
#   is  → "你俩是不是同一个人？"
#   ==  → "你俩长得是不是一样？"

print("\n=== 身份运算符 is ===")

a = [1, 2, 3]
b = [1, 2, 3]
c = a

print(f"a == b → {a == b}")    # True（值相同）
print(f"a is b → {a is b}")    # False（不是同一个对象）
print(f"a is c → {a is c}")    # True（c 就是 a，同一个对象）

# is 最常见的用法：判断是否为 None
result = None
print(f"\nresult is None → {result is None}")          # True（推荐）
print(f"result is not None → {result is not None}")    # False

# ============================================================
# 五、位运算符（了解即可）
# ============================================================
#
# 位运算是对数字的二进制位进行操作。
# 日常编程不太常用，但面试可能会问到。

print("\n=== 位运算符（了解即可） ===")

a = 0b1010   # 二进制的 10
b = 0b1100   # 二进制的 12

print(f"a = {a} (二进制: {bin(a)})")
print(f"b = {b} (二进制: {bin(b)})")

print(f"a & b  按位与：{a & b}  (二进制: {bin(a & b)})")   # 1000 = 8
print(f"a | b  按位或：{a | b}  (二进制: {bin(a | b)})")   # 1110 = 14
print(f"a ^ b  按位异或：{a ^ b} (二进制: {bin(a ^ b)})")  # 0110 = 6
print(f"~a     按位取反：{~a}")                              # -11
print(f"a << 1 左移一位：{a << 1} (相当于 ×2)")              # 20
print(f"a >> 1 右移一位：{a >> 1} (相当于 ÷2)")              # 5

