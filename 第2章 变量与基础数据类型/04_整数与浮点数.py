# ============================================================
# 第2章 · 04 - 整数（int）与浮点数（float）
# ============================================================
#
# 现实世界里有两种常见的数字：
#   整数：没有小数点的数，比如 1, 100, -5, 0
#   小数：有小数点的数，比如 3.14, -0.5, 100.0
#
# Python 里管它们叫：
#   int（integer 的缩写）= 整数
#   float（浮点数）= 小数
#
# ============================================================

# --- 整数 int ---
print("=== 整数 int ===")

age = 18
temperature = -5
population = 1400000000

print("年龄：", age)
print("温度：", temperature)
print("人口：", population)

# Python 的整数没有大小限制，多大都行
big_number = 99999999999999999999999999999999
print("超大整数：", big_number)

# 大数字可以用下划线分隔，方便阅读（Python 3.6+）
world_population = 8_000_000_000
print("世界人口：", world_population)

# --- 浮点数 float ---
print("\n=== 浮点数 float ===")

pi = 3.14159
weight = 65.5
price = -9.9

print("圆周率：", pi)
print("体重：", weight)
print("折扣：", price)

# 注意：100 和 100.0 是不一样的类型！
print("\n=== 整数 vs 浮点数 ===")
a = 100      # 这是整数
b = 100.0    # 这是浮点数（虽然值看起来一样）
print("a =", a, "，类型是", type(a))
print("b =", b, "，类型是", type(b))

# --- 基本数学运算 ---
print("\n=== 基本数学运算 ===")

print("加法：3 + 2 =", 3 + 2)
print("减法：10 - 4 =", 10 - 4)
print("乘法：6 * 7 =", 6 * 7)

# 除法——重点注意！
print("\n--- 除法相关 ---")
print("普通除法：7 / 2 =", 7 / 2)       # 结果是 3.5（永远返回浮点数）
print("整数除法：7 // 2 =", 7 // 2)      # 结果是 3（只保留整数部分，向下取整）
print("取余数：  7 % 2 =", 7 % 2)        # 结果是 1（除不尽的部分）

# 生活中的例子：7 个苹果分给 2 个人
# 每人分到 7 // 2 = 3 个，剩下 7 % 2 = 1 个

print("\n--- 乘方（幂运算） ---")
print("2 的 3 次方：2 ** 3 =", 2 ** 3)   # 2 × 2 × 2 = 8
print("3 的平方：  3 ** 2 =", 3 ** 2)    # 3 × 3 = 9
print("4 的平方根：4 ** 0.5 =", 4 ** 0.5)  # √4 = 2.0

# --- 浮点数的精度问题 ---
print("\n=== ⚠️ 浮点数的小秘密 ===")

result = 0.1 + 0.2
print("0.1 + 0.2 =", result)
# 你可能会看到 0.30000000000000004，而不是 0.3
# 这不是 Python 的 bug，而是计算机存储小数的方式导致的
# 就像你用十进制写不完 1/3 = 0.33333...一样
# 计算机用二进制也写不完某些小数

# 解决办法：用 round() 四舍五入
print("四舍五入后：", round(0.1 + 0.2, 1))  # 保留1位小数

# --- 数字的一些有用函数 ---
print("\n=== 常用数字函数 ===")

print("绝对值：abs(-42) =", abs(-42))
print("最大值：max(3, 7, 1) =", max(3, 7, 1))
print("最小值：min(3, 7, 1) =", min(3, 7, 1))
print("四舍五入：round(3.14159, 2) =", round(3.14159, 2))

# --- 核心总结 ---
# 1. int = 整数，没有小数点
# 2. float = 浮点数，有小数点
# 3. 除法 / 永远返回 float，整除用 //，取余用 %
# 4. ** 是乘方运算
# 5. 浮点数有精度问题，需要注意
