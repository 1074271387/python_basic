# ============================================================
# 第4章 · 07 - 嵌套循环与经典练习
# ============================================================
#
# 嵌套循环 = 循环里面套循环。
# 外层循环每执行一次，内层循环完整执行一轮。
#
# 生活类比：
#   外层循环 = 翻日历的"月"
#   内层循环 = 翻日历的"天"
#   每过一个月（外层），要过完那个月的每一天（内层）
#
# 对比其他语言：
#   嵌套循环在所有语言中都一样，只是语法差异。
#   Java: for (int i...) { for (int j...) { } }
#   Python: for i in ...:  →  for j in ...:
#
# ============================================================

# ============================================================
# 一、嵌套循环基础
# ============================================================

print("=== 嵌套循环基础 ===")

# 外层3次 × 内层4次 = 总共12次
for i in range(1, 4):       # 外层：1, 2, 3
    for j in range(1, 5):   # 内层：1, 2, 3, 4
        print(f"({i},{j})", end=" ")
    print()  # 内层结束后换行

# 理解执行顺序：
# i=1 → j=1,2,3,4 → 换行
# i=2 → j=1,2,3,4 → 换行
# i=3 → j=1,2,3,4 → 换行

# ============================================================
# 二、经典练习1：九九乘法表
# ============================================================
#
# 这是嵌套循环最经典的入门练习！

print("\n=== 九九乘法表 ===")

for i in range(1, 10):           # 第一个因子：1-9
    for j in range(1, i + 1):    # 第二个因子：1 到 i
        print(f"{j}×{i}={i*j:2d}", end="  ")
    print()

# 关键点：内层循环的终点是 i+1，所以每行打印的列数递增
# i=1 → j=1
# i=2 → j=1,2
# i=3 → j=1,2,3
# ...

