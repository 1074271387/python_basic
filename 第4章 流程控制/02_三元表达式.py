# ============================================================
# 第4章 · 02 - 三元表达式（条件表达式）
# ============================================================
#
# 三元表达式是 if-else 的"一行版"。
# 当 if-else 只是为了给变量赋值时，用三元表达式更简洁。
#
# 语法：
#   值1 if 条件 else 值2
#   → 条件为 True 返回 值1，否则返回 值2
#
# 对比其他语言：
#   Java / JS → condition ? value1 : value2
#   Python    → value1 if condition else value2
#   注意：Python 的顺序和其他语言不同！"值"在前，"条件"在中间。
#
# ============================================================

# ============================================================
# 一、基础用法
# ============================================================

print("=== 基础用法 ===")

age = 20

# 传统 if-else（4行）
if age >= 18:
    status = "成年"
else:
    status = "未成年"
print(f"传统写法：{status}")

# 三元表达式（1行）
status = "成年" if age >= 18 else "未成年"
print(f"三元表达式：{status}")

# 两种写法完全等价，三元表达式更简洁

# ============================================================
# 二、直接用在 print / f-string 中
# ============================================================

print("\n=== 在表达式中使用 ===")

score = 85

# 直接在 print 中使用
print("成绩：" + ("及格" if score >= 60 else "不及格"))

# 在 f-string 中使用（需要加括号）
print(f"成绩：{'及格' if score >= 60 else '不及格'}")

# 在列表中使用
nums = [1, -2, 3, -4, 5]
labels = ["正数" if n > 0 else "负数或零" for n in nums]
print(f"\n数字：{nums}")
print(f"标签：{labels}")

# ============================================================
# 三、赋值场景（最常用）
# ============================================================

print("\n=== 赋值场景 ===")

# 场景1：根据条件选值
temperature = 35
drink = "冰饮" if temperature > 30 else "热饮"
print(f"温度 {temperature}°C → 推荐：{drink}")

# 场景2：处理边界情况
user_input = ""
username = user_input if user_input else "匿名用户"
print(f"用户名：{username}")

# 场景3：取两个值中较大/较小的
a, b = 10, 25
maximum = a if a > b else b
minimum = a if a < b else b
print(f"a={a}, b={b}")
print(f"最大值：{maximum}，最小值：{minimum}")
# 当然，Python 有内置函数：max(a, b) 和 min(a, b)

# ============================================================
# 四、嵌套三元表达式（谨慎使用）
# ============================================================

print("\n=== 嵌套三元表达式 ===")

score = 85

# 嵌套三元（能用但不推荐太深）
grade = "A" if score >= 90 else "B" if score >= 80 else "C" if score >= 70 else "D"
print(f"分数 {score} → 等级 {grade}")

# 等价的 if-elif-else（更清晰）：
# if score >= 90:
#     grade = "A"
# elif score >= 80:
#     grade = "B"
# elif score >= 70:
#     grade = "C"
# else:
#     grade = "D"

# ⚠️ 嵌套超过2层就不如用 if-elif-else 了
# 代码是写给人看的，清晰比简短更重要！

# ============================================================
# 五、三元表达式 vs or 短路（进阶技巧）
# ============================================================

print("\n=== or 短路赋值 ===")

# Python 的 or 有"短路求值"特性：
# A or B → 如果 A 为真值，返回 A；否则返回 B

name = "" or "默认名字"
print(f'name = "" or "默认名字" → {name}')

count = 0 or 100
print(f"count = 0 or 100 → {count}")
