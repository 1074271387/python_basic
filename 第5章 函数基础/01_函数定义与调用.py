# ============================================================
# 第5章 · 01 - 函数定义与调用
# ============================================================
#
# 函数 = 把一段可复用的代码"打包"起来，起个名字，需要时再调用。
#
# 生活类比：
#   你把"泡咖啡"这件事写成一张卡片（函数定义），
#   每次想喝咖啡时，只需要喊一声"泡咖啡！"（函数调用）。
#
# 对比其他语言：
#   Java → public static void greet() { ... }
#   JS   → function greet() { ... }  或  const greet = () => { ... }
#   Python → def greet():   简洁、无需声明返回类型
#
# ============================================================

# ============================================================
# 一、最简单的函数：无参数、无返回值
# ============================================================

print("=== 最简单的函数 ===")

def say_hello():
    """向世界问好（这是文档字符串 docstring）"""
    print("Hello, World!")

# 定义了函数之后，不调用就不会执行
say_hello()   # 调用：函数名 + ()
say_hello()   # 可以反复调用

# ⚠️ 常见错误
# say_hello     ← 没有括号，不会执行！只是引用了函数对象
# print(say_hello)  → <function say_hello at 0x...>

# ============================================================
# 二、带参数的函数
# ============================================================

print("\n=== 带参数的函数 ===")

def greet(name):
    """根据名字打招呼"""
    print(f"你好，{name}！欢迎学 Python！")

greet("小明")
greet("Alice")

# Python 不需要声明参数类型（动态类型语言）
# 对比 Java：public static void greet(String name) { ... }

# ============================================================
# 三、带多个参数的函数
# ============================================================

print("\n=== 多个参数 ===")

def add(a, b):
    """计算两个数的和"""
    result = a + b
    print(f"{a} + {b} = {result}")

add(3, 5)
add(10, 20)

# ============================================================
# 四、带返回值的函数
# ============================================================

print("\n=== 带返回值 ===")

def multiply(a, b):
    """返回两个数的乘积"""
    return a * b      # return 把结果交给调用者

result = multiply(4, 5)
print(f"4 × 5 = {result}")

# 可以直接在表达式中使用
print(f"3 × 7 = {multiply(3, 7)}")

# 没有 return 的函数，默认返回 None
def do_nothing():
    pass    # pass 是占位符，表示"什么都不做"

print(f"do_nothing() 的返回值：{do_nothing()}")  # None

# ============================================================
# 五、函数的调用顺序
# ============================================================
#
# Python 是从上到下执行的：
#   - 函数必须先定义，后调用
#   - 定义时不执行函数体，调用时才执行

print("\n=== 调用顺序 ===")

def step1():
    print("第1步：准备材料")

def step2():
    print("第2步：开始制作")

def step3():
    print("第3步：完成！")

# 按顺序调用
step1()
step2()
step3()

# ============================================================
# 六、函数嵌套调用
# ============================================================

print("\n=== 函数嵌套调用 ===")

def get_full_name(first, last):
    """拼接全名"""
    return f"{first} {last}"

def greet_person(first, last):
    """用全名打招呼 —— 内部调用了 get_full_name"""
    full_name = get_full_name(first, last)
    print(f"Hello, {full_name}!")

greet_person("张", "三")
greet_person("Li", "Ming")

# ============================================================
# 七、文档字符串 docstring
# ============================================================

print("\n=== 文档字符串 ===")

def calculate_bmi(weight, height):
    """
    计算 BMI 指数。

    参数：
        weight: 体重（千克）
        height: 身高（米）

    返回：
        float: BMI 值
    """
    return weight / (height ** 2)

bmi = calculate_bmi(70, 1.75)
print(f"BMI = {bmi:.1f}")

# 查看函数的文档字符串
print(f"\n函数文档：{calculate_bmi.__doc__}")

