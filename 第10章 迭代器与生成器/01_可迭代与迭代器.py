# ============================================================
# 第10章 · 01 - 迭代器（Iterator）
# ============================================================
#
# 一句话：迭代器就是"能一个一个吐元素，吐完就没了"的东西。
#
# 关键动作只有两个：
#   iter(x)   把列表/字符串等变成迭代器
#   next(it)  从迭代器里取下一个，取光了报 StopIteration
#
# for 循环本质上就是在偷偷帮你做这两件事。
# ============================================================


# ----- 案例1：手动用 next() 取元素 -----
print("=== 案例1：手动 next ===")

nums = [10, 20, 30]
it = iter(nums)          # 列表 → 迭代器

print(next(it))          # 10
print(next(it))          # 20
print(next(it))          # 30
# print(next(it))        # 再取就会报 StopIteration（没东西了）


# ----- 案例2：for 循环其实就是上面的过程 -----
print("\n=== 案例2：for 等价写法 ===")

it = iter(nums)
while True:
    try:
        x = next(it)     # 取下一个
    except StopIteration:
        break            # 取光了就退出
    print(x)


# ----- 记住一句话 -----
# 迭代器"用一次就空了"，不能倒回去重头取。
print("\n=== 迭代器用完就空 ===")
it = iter([1, 2, 3])
print("第一次遍历:", list(it))   # [1, 2, 3]
print("第二次遍历:", list(it))   # []  ← 已经空了
