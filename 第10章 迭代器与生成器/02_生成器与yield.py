# ============================================================
# 第10章 · 02 - 生成器与 yield（重点）
# ============================================================
#
# 生成器 = "自己写出来的迭代器"，但写法超简单：
#   只要函数里有 yield，它就是生成器函数。
#
# yield 和 return 的区别：
#   return → 给一个结果，函数直接结束
#   yield  → 吐一个结果，函数"暂停"在这，下次接着往下跑
# ============================================================


# ----- 案例1：第一个生成器 -----
print("=== 案例1：第一个生成器 ===")


def count_to(n):
    i = 1
    while i <= n:
        yield i          # 吐出 i，然后暂停在这里
        i += 1


for x in count_to(3):
    print(x)             # 1 2 3


# ----- 案例2：看清 yield 的"暂停"特性 -----
print("\n=== 案例2：yield 会暂停 ===")


def steps():
    print("  开始")
    yield "A"            # 跑到这暂停
    print("  继续")
    yield "B"            # 再次暂停
    print("  结束")


g = steps()             # 此时函数一行都没跑
print(next(g))          # 打印"开始"，再返回 A
print(next(g))          # 打印"继续"，再返回 B


# ----- 案例3：迭代器 vs 生成器，到底差在哪 -----
print("\n=== 案例3：两种写法对比 ===")

# 写法A：列表——先把所有结果算好，全部放内存
squares_list = [x * x for x in range(5)]
print("列表  :", squares_list)        # 直接看到全部 [0,1,4,9,16]

# 写法B：生成器——要一个才算一个，省内存
squares_gen = (x * x for x in range(5))   # 圆括号 = 生成器表达式
print("生成器:", squares_gen)         # 只是个对象，还没开始算
print("取值  :", list(squares_gen))   # 用的时候才一个个算出来

# 结论：
#   数据少、要反复用     → 用列表
#   数据多、只过一遍     → 用生成器（不撑爆内存）
